"""Behavioral tests, with expectations independent of production helpers."""
import copy
import unittest
from fractions import Fraction
from a2_v0 import model as m, measurement as e


class CoreTests(unittest.TestCase):
    def setUp(self):
        self.assertTrue(hasattr(m, 'Learner'), 'finite model is not implemented')
        self.assertTrue(hasattr(e, 'measure'), 'frontier verifier is not implemented')

    def test_channel_coordinate_order_and_inverse(self):
        # Catches reversed sigma direction, wrong mask indexing, or LSB ordering.
        h = m.Hypothesis((2, 0, 1), (1, 0, 1))
        self.assertEqual(m.channel(h, 6), (1, 1, 0))  # x=110
        self.assertEqual(m.decode(h, (1, 1, 0)), 6)
        self.assertEqual(m.decode(h, (0, 0, 0)), 3)

    def test_feedback_updates_and_fixed_work(self):
        # Catches inverted correctness predicates and result-dependent loop work.
        learner = m.Learner()
        report = learner.update((0, 0, 1), 1, m.Feedback(True, False))
        self.assertNotIn(0, learner.live)
        self.assertIn(1, learner.live)
        self.assertEqual(learner.active, 1)
        self.assertEqual(report.hypothesis_checks, 48)
        self.assertEqual(report.charge, 1)
        learner.update((0, 0, 1), 0, m.Feedback(True, True))
        self.assertEqual(learner.active, 1)
        self.assertTrue(all(m.decode(m.HYPOTHESES[i], (0, 0, 1)) == 0
                            for i in learner.live))

    def test_invalid_feedback_is_processed_but_cannot_learn(self):
        learner = m.Learner()
        before = learner.snapshot()
        report = learner.update((0, 0, 1), 1, m.Feedback(False, False))
        self.assertEqual(learner.snapshot(), before)
        self.assertEqual(report.hypothesis_checks, 48)
        self.assertEqual(report.charge, 1)

    def test_clones_and_frozen_constructor_do_not_leak_learning_state(self):
        first = m.Learner()
        second = copy.deepcopy(first)
        first.update((0, 0, 1), 1, m.Feedback(True, False))
        self.assertEqual(len(second.live), 48)
        frozen = first.freeze()
        self.assertEqual(frozen.active, 1)
        self.assertEqual(set(frozen.__slots__), {'task', 'active'})
        self.assertFalse(hasattr(frozen, 'live'))
        with self.assertRaises(m.InvalidAssay):
            first.update((0, 0, 1), 0, m.Feedback(True, True))

    def test_constructor_realizes_only_one_diagnostic_policy(self):
        policies = m.realize(m.ConstructorInput(active=1))
        self.assertEqual(len(policies), 9)
        self.assertEqual([p.target for p in policies[:8]], list(range(8)))
        self.assertEqual(policies[-1].hypothesis, 1)
        self.assertTrue(all(p.realization_cost == 1 for p in policies))
        self.assertEqual(policies[-1].action(()), ('q', 0))
        self.assertEqual(policies[-1].action((0, 0, 1)), ('r', 0))

    def test_actual_execution_charges_realization_and_repairs(self):
        policies = m.realize(m.ConstructorInput(active=1))
        immediate = m.execute(policies[0], m.HYPOTHESES[1], 0)
        diagnostic = m.execute(policies[-1], m.HYPOTHESES[1], 0)
        self.assertTrue(immediate.success)
        self.assertEqual(immediate.cost, 2)
        self.assertEqual(immediate.actions, (('r', 0),))
        self.assertTrue(diagnostic.success)
        self.assertEqual(diagnostic.cost, 5)
        self.assertEqual(diagnostic.actions, (('q', 0), ('q', 1), ('q', 2), ('r', 0)))

    def test_frontiers_are_enumerated_with_reusable_policy_witnesses(self):
        wrong = e.measure(1, m.ConstructorInput(active=0))
        right = e.measure(1, m.ConstructorInput(active=1))
        self.assertEqual(wrong.frontier, (0, 1, 2, 4, 8, 16, 32, 64, 128))
        self.assertEqual(right.frontier, tuple(range(256)))
        self.assertEqual(wrong.subsets_checked, 256)
        self.assertEqual(len(wrong.executions), 9)
        self.assertEqual(len(wrong.executions[0]), 8)
        self.assertNotIn(3, wrong.frontier)  # Cannot choose a different repair per x.

    def test_weighted_utility_is_exact_and_uses_default_policy(self):
        wrong = e.measure(1, m.ConstructorInput(active=0))
        right = e.measure(1, m.ConstructorInput(active=1))
        self.assertEqual(e.utility(wrong), Fraction(0))
        self.assertEqual(e.utility(right), Fraction(1))
        self.assertEqual(e.weighted_success((0, 7)), Fraction(129, 255))

    def test_independent_oracle_and_downward_closure(self):
        # Hand-set success pair {000,111}; this is not generated by measure().
        expected = (0, 1, 2, 4, 8, 16, 32, 64, 128, 129)
        self.assertEqual(e.oracle_frontier((0, 7)), expected)
        self.assertTrue(e.downward_closed(expected))
        self.assertFalse(e.downward_closed((0, 3)))


if __name__ == '__main__':
    unittest.main()
